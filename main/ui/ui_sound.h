// main/ui/ui_sound.h —— 界面提示音：短促、可静音、不阻塞界面。
//
// 番茄钟阶段切换、作息节点切换与计时器到点共用同一段提示音。播放放在一次性任务里，
// 不占用 LVGL 任务与按键回调的时间；设置里静音时不发声，音量取设置里的档位。
#pragma once

// 播放一次提示音。音频未初始化或已静音时静默返回。重复调用会被合并成一次。
void ui_sound_beep(void);

// 把当前的音量/静音设置应用到音频输出。静音时把音量置 0——这样即使某条发声路径
// 忘了自行判断静音，也听不到声音，静音才是真正全局的。
// 音频尚未打开时只记录到 BSP，待 codec 打开时由 BSP 生效。
// 修改设置页或快捷面板的音量/静音后必须调用它，否则改动要等下次打开音频才生效。
void ui_sound_apply_volume(void);
